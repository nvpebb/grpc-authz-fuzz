#!/usr/bin/env bash
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$ROOT"

export PATH="${ROOT}/.tools/bin:${PATH}"
export CONAN_HOME="${CONAN_HOME:-${ROOT}/.conan2}"
mkdir -p "$CONAN_HOME" build

if ! command -v conan >/dev/null 2>&1; then
  echo "Conan not found. Install with: UV_TOOL_DIR=$ROOT/.tools UV_TOOL_BIN_DIR=$ROOT/.tools/bin uv tool install conan"
  exit 1
fi

if [[ ! -f "$CONAN_HOME/profiles/default" ]]; then
  conan profile detect --force
fi

echo "==> conan install (first run may compile grpc/openssl from source; can take a long time)"
conan install . -of build -s build_type=Release --build=missing

echo "==> cmake configure + build"
# drop stale stubs if they were generated by a mismatched system protoc
rm -rf build/build/Release/proto
cmake --preset conan-release
cmake --build --preset conan-release -j"$(nproc)"

echo "==> ctest"
ctest --preset conan-release --output-on-failure

echo "==> notes smoke"
./build/build/Release/src/grpc-authz-fuzz --notes-smoke
